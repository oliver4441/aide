#!/usr/bin/env node
/**
 * Merge SHA-256 checksums of a directory of release assets into
 * public/apk-checksums.json, keyed by release tag then asset filename.
 *
 *   node scripts/update-checksums.mjs <asset-dir> <tag>
 *
 * The /downloads page reads that file and shows a copyable hash per asset.
 * It is written by CI right after a release is published, because a hash can
 * only be computed from the exact bytes that were uploaded — hashing them
 * later by hand is how a checksum file silently drifts out of date.
 *
 * Only the tag being published is replaced. Existing entries are preserved so
 * older releases keep their published hashes.
 */
import { createHash } from "node:crypto";
import { createReadStream, readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";

const [dir, tag] = process.argv.slice(2);

if (!dir || !tag) {
  console.error("usage: node scripts/update-checksums.mjs <asset-dir> <tag>");
  process.exit(1);
}

const CHECKSUMS_PATH = resolve("public/apk-checksums.json");

const sha256 = (path) =>
  new Promise((res, rej) => {
    const hash = createHash("sha256");
    createReadStream(path)
      .on("data", (chunk) => hash.update(chunk))
      .on("error", rej)
      .on("end", () => res(hash.digest("hex")));
  });

const files = readdirSync(dir)
  .map((name) => join(dir, name))
  .filter((path) => statSync(path).isFile() && !path.endsWith(".sha256"));

if (files.length === 0) {
  console.error(`no files to hash in ${dir}`);
  process.exit(1);
}

const entries = {};
for (const path of files.sort()) {
  entries[basename(path)] = await sha256(path);
  console.log(`${basename(path)}  ${entries[basename(path)]}`);
}

let json = { releases: {} };
try {
  json = JSON.parse(readFileSync(CHECKSUMS_PATH, "utf8"));
} catch {
  // First run, or the file was removed — start from an empty map.
}

json._comment =
  "SHA-256 checksums of published Aide release assets (APK and desktop), keyed by release tag then asset filename. Generated by .github/workflows after each release.";
json.releases = { ...(json.releases ?? {}), [tag]: entries };

writeFileSync(CHECKSUMS_PATH, `${JSON.stringify(json, null, 2)}\n`);

console.log(`\nwrote ${Object.keys(entries).length} checksums for ${tag} to ${CHECKSUMS_PATH}`);
